import { FORWARD_AUTH_MIDDLEWARE, quoteDynamicValue } from './dynamic.ts'
import { type ProtectionStore, protectionForHost } from './protections.ts'

/**
 * A hostname alias is a nickname, never a rename.
 *
 * Docker cannot rewrite a label on a running container, and driving Compose
 * from the panel is out (ADR 0001), so an alias can only ever *add* a router
 * beside the project's own. Both hostnames answer, which is the correct
 * behaviour and is documented as such rather than filed as a bug.
 */
export interface StoredAlias {
  /** Compose project the alias belongs to; kept so a whole project can be dropped. */
  project: string
  /** Compose service, for display and for removing one alias. */
  service: string
  /** Container name, never the Compose service alias: two projects can both have `web`. */
  container: string
  host: string
  port: number
  entryPoint: string
  /** The hostname is outside every domain the gateway serves: a domain the user pointed here. */
  custom?: boolean
  /**
   * ACME resolver named on the router itself.
   *
   * Set only for a custom domain on a gateway whose entrypoint resolver issues over DNS-01: that
   * resolver's DNS provider does not control the user's domain, so the router asks for HTTP-01.
   */
  certResolver?: string
}

/** Name of the HTTP-01 resolver that profiles/remote-tls-dns.yaml defines beside the default one. */
export const HTTP_CERT_RESOLVER = 'letsencrypthttp'

export const ALIASES_MARKER = '# portta-aliases: '

const HEADER = [
  '# ============================================================================',
  '# Generated by Portta panel. Edits are overwritten.',
  '# ============================================================================',
  "# Hostname aliases: one additional router per aliased service. The project's",
  '# own router is never touched, so both hostnames answer. See docs/product/guides/web-ui.md.',
  '# ============================================================================',
]

/**
 * One router per hostname. The first alias of a service keeps the name it always had, so a file
 * written before a service could have several is not rewritten into new routers.
 */
export function aliasRouterName(project: string, service: string, index = 0): string {
  const base = `portta-alias-${project}-${service}`.replace(/[^a-zA-Z0-9-]/g, '-')
  return index === 0 ? base : `${base}-${index + 1}`
}

/**
 * The router name of each alias, unique across the whole file.
 *
 * Names are built from project and service with dashes, so `web` second and a service called
 * `web-2` first would spell the same name, and Traefik would drop one router silently. A name
 * already taken moves on to the next free index instead.
 */
function routerNames(aliases: StoredAlias[]): string[] {
  const seen = new Map<string, number>()
  const taken = new Set<string>()
  return aliases.map((alias) => {
    const key = `${alias.project}\u0000${alias.service}`
    let index = seen.get(key) ?? 0
    let name = aliasRouterName(alias.project, alias.service, index)
    while (taken.has(name)) name = aliasRouterName(alias.project, alias.service, ++index)
    seen.set(key, index + 1)
    taken.add(name)
    return name
  })
}

/**
 * The canonical Traefik file renderer, used by both the panel and the CLI.
 *
 * On a public host (`forwardAuth`) every alias passes through ForwardAuth, so a
 * hostname nobody decided about is closed, exactly like the project's own.
 */
export function renderAliases(aliases: StoredAlias[], forwardAuth = false, suspended: StoredAlias[] = []): string {
  // A suspended alias stays in the stored state, so it returns when its conflict is gone, but has no router.
  const lines = [...HEADER, `${ALIASES_MARKER}${JSON.stringify([...aliases, ...suspended])}`, '']
  if (aliases.length === 0) {
    lines.push('# No alias is set. A project is reached on the hostname it derives.')
    return `${lines.join('\n')}\n`
  }

  const names = routerNames(aliases)
  lines.push('http:', '  routers:')
  aliases.forEach((alias, position) => {
    const router = names[position]!
    lines.push(`    ${router}:`)
    lines.push(`      rule: ${quoteDynamicValue(`Host(\`${alias.host}\`)`)}`)
    lines.push(`      entryPoints: [${alias.entryPoint}]`)
    if (forwardAuth) lines.push(`      middlewares: [${FORWARD_AUTH_MIDDLEWARE}]`)
    lines.push(`      service: ${router}`)
    if (alias.certResolver) lines.push('      tls:', `        certResolver: ${quoteDynamicValue(alias.certResolver)}`)
  })

  lines.push('  services:')
  aliases.forEach((alias, position) => {
    const router = names[position]!
    lines.push(`    ${router}:`, '      loadBalancer:', '        servers:')
    lines.push(`          - url: ${quoteDynamicValue(`http://${alias.container}:${alias.port}`)}`)
  })

  lines.push('')
  return lines.join('\n')
}

/**
 * The file every writer renders, so none can undo a suspension.
 *
 * On a public host an alias whose hostname carries a decision made for another
 * service would inherit it, so it keeps its stored state but has no router until
 * the conflict is gone.
 */
export function renderAliasesForStore(
  aliases: StoredAlias[],
  store: ProtectionStore,
  publicHost: boolean,
  previousStore?: ProtectionStore,
): string {
  const conflicts = (alias: StoredAlias): boolean => {
    return [store, ...(previousStore ? [previousStore] : [])].some((candidate) => {
      const decided = protectionForHost(candidate, alias.host)
      return decided !== null && (decided.service !== alias.service || decided.project !== alias.project)
    })
  }
  const suspended = publicHost ? aliases.filter(conflicts) : []
  return renderAliases(
    aliases.filter((alias) => !suspended.includes(alias)),
    publicHost,
    suspended,
  )
}

/** Reads the state back out of the file the panel itself wrote. */
export function parseAliases(contents: string | null): StoredAlias[] {
  if (!contents) return []
  const line = contents.split('\n').find((entry) => entry.startsWith(ALIASES_MARKER))
  if (!line) return []
  try {
    const parsed = JSON.parse(line.slice(ALIASES_MARKER.length)) as unknown
    if (!Array.isArray(parsed)) return []
    return parsed.filter((entry): entry is StoredAlias => {
      const value = entry as Record<string, unknown>
      return typeof value?.host === 'string' && typeof value?.container === 'string'
    })
  } catch {
    return []
  }
}
